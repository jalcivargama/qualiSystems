-- Catalogo de sistemas y dependencias
-- PostgreSQL 10+

CREATE TABLE catalog_component (
    component_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_type VARCHAR(30) NOT NULL
        CHECK (component_type IN ('SYSTEM', 'API', 'DATABASE', 'INFRASTRUCTURE', 'EXTERNAL_SERVICE', 'MESSAGING')),
    name VARCHAR(200) NOT NULL,
    acronym VARCHAR(50),
    description TEXT,
    is_active CHAR(1) NOT NULL DEFAULT 'Y'
        CHECK (is_active IN ('Y', 'N')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (component_type, name),
    UNIQUE (component_id, component_type)
);

CREATE TABLE system_detail (
    component_id BIGINT PRIMARY KEY,
    component_type VARCHAR(30) NOT NULL DEFAULT 'SYSTEM' CHECK (component_type = 'SYSTEM'),
    business_objective TEXT,
    owner_area VARCHAR(200),
    criticality VARCHAR(20)
        CHECK (criticality IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    system_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (system_status IN ('PLANNED', 'ACTIVE', 'DEPRECATED', 'RETIRED')),
    go_live_date DATE,
    end_of_life_date DATE,
    FOREIGN KEY (component_id, component_type)
        REFERENCES catalog_component (component_id, component_type) ON DELETE CASCADE,
    CHECK (end_of_life_date IS NULL OR go_live_date IS NULL OR end_of_life_date >= go_live_date)
);

CREATE TABLE api_detail (
    component_id BIGINT PRIMARY KEY,
    component_type VARCHAR(30) NOT NULL DEFAULT 'API' CHECK (component_type = 'API'),
    api_version VARCHAR(50),
    url VARCHAR(2000),
    protocol VARCHAR(30),
    authentication_method VARCHAR(100),
    sla_description TEXT,
    FOREIGN KEY (component_id, component_type)
        REFERENCES catalog_component (component_id, component_type) ON DELETE CASCADE
);

CREATE TABLE database_detail (
    component_id BIGINT PRIMARY KEY,
    component_type VARCHAR(30) NOT NULL DEFAULT 'DATABASE' CHECK (component_type = 'DATABASE'),
    engine VARCHAR(100) NOT NULL,
    engine_version VARCHAR(100),
    instance_name VARCHAR(200),
    schema_name VARCHAR(200),
    FOREIGN KEY (component_id, component_type)
        REFERENCES catalog_component (component_id, component_type) ON DELETE CASCADE
);

CREATE TABLE infrastructure_detail (
    component_id BIGINT PRIMARY KEY,
    component_type VARCHAR(30) NOT NULL DEFAULT 'INFRASTRUCTURE'
        CHECK (component_type = 'INFRASTRUCTURE'),
    hostname VARCHAR(255),
    ip_address VARCHAR(45),
    operating_system VARCHAR(200),
    hosting_model VARCHAR(20)
        CHECK (hosting_model IN ('CLOUD', 'ON_PREMISE')),
    FOREIGN KEY (component_id, component_type)
        REFERENCES catalog_component (component_id, component_type) ON DELETE CASCADE
);

CREATE TABLE system_deployment (
    deployment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_id BIGINT NOT NULL REFERENCES system_detail (component_id) ON DELETE CASCADE,
    environment VARCHAR(20) NOT NULL
        CHECK (environment IN ('DEVELOPMENT', 'TEST', 'QA', 'STAGING', 'PRODUCTION', 'DR')),
    url VARCHAR(2000),
    UNIQUE (component_id, environment)
);

CREATE TABLE person (
    person_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(200) NOT NULL,
    email VARCHAR(320),
    organization VARCHAR(200),
    is_active CHAR(1) NOT NULL DEFAULT 'Y'
        CHECK (is_active IN ('Y', 'N')),
    UNIQUE (email)
);

CREATE TABLE responsibility_role (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code VARCHAR(40) NOT NULL UNIQUE,
    role_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE system_responsibility (
    component_id BIGINT NOT NULL REFERENCES system_detail (component_id) ON DELETE CASCADE,
    person_id BIGINT NOT NULL REFERENCES person (person_id),
    role_id BIGINT NOT NULL REFERENCES responsibility_role (role_id),
    notes TEXT,
    PRIMARY KEY (component_id, person_id, role_id)
);

CREATE TABLE technology (
    technology_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(30) NOT NULL
        CHECK (category IN ('LANGUAGE', 'FRAMEWORK', 'DATABASE', 'FRONTEND', 'BACKEND',
                            'MESSAGING', 'CONTAINER', 'ORCHESTRATION', 'MONITORING', 'OTHER')),
    name VARCHAR(200) NOT NULL,
    UNIQUE (category, name)
);

CREATE TABLE component_technology (
    component_id BIGINT NOT NULL REFERENCES catalog_component (component_id) ON DELETE CASCADE,
    technology_id BIGINT NOT NULL REFERENCES technology (technology_id),
    version VARCHAR(100),
    is_primary CHAR(1) NOT NULL DEFAULT 'N'
        CHECK (is_primary IN ('Y', 'N')),
    PRIMARY KEY (component_id, technology_id)
);

CREATE TABLE dependency_type (
    dependency_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_code VARCHAR(40) NOT NULL UNIQUE,
    type_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE dependency (
    dependency_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin_component_id BIGINT NOT NULL REFERENCES catalog_component (component_id),
    target_component_id BIGINT NOT NULL REFERENCES catalog_component (component_id),
    dependency_type_id BIGINT NOT NULL REFERENCES dependency_type (dependency_type_id),
    dependency_scope VARCHAR(10) NOT NULL
        CHECK (dependency_scope IN ('INTERNAL', 'EXTERNAL')),
    criticality VARCHAR(20)
        CHECK (criticality IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (origin_component_id <> target_component_id)
);

CREATE TABLE data_flow (
    data_flow_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dependency_id BIGINT NOT NULL REFERENCES dependency (dependency_id) ON DELETE CASCADE,
    data_name VARCHAR(200) NOT NULL,
    periodicity VARCHAR(100),
    sensitivity VARCHAR(20)
        CHECK (sensitivity IN ('PUBLIC', 'INTERNAL', 'CONFIDENTIAL', 'RESTRICTED')),
    data_format VARCHAR(100),
    description TEXT
);

CREATE INDEX ix_dependency_origin ON dependency (origin_component_id);
CREATE INDEX ix_dependency_target ON dependency (target_component_id);
CREATE INDEX ix_dependency_type ON dependency (dependency_type_id);
CREATE INDEX ix_system_resp_person ON system_responsibility (person_id);
CREATE INDEX ix_component_tech_technology ON component_technology (technology_id);
CREATE INDEX ix_data_flow_dependency ON data_flow (dependency_id);

