-- Catalogo de sistemas y dependencias
-- Oracle Database 12c+

CREATE TABLE catalog_component (
    component_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_type VARCHAR2(30) NOT NULL
        CHECK (component_type IN ('SYSTEM', 'API', 'DATABASE', 'INFRASTRUCTURE', 'EXTERNAL_SERVICE', 'MESSAGING')),
    name VARCHAR2(200) NOT NULL,
    acronym VARCHAR2(50),
    description CLOB,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL
        CHECK (is_active IN ('Y', 'N')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UNIQUE (component_type, name),
    UNIQUE (component_id, component_type)
);

CREATE TABLE system_detail (
    component_id NUMBER(19) PRIMARY KEY,
    component_type VARCHAR2(30) DEFAULT 'SYSTEM' NOT NULL CHECK (component_type = 'SYSTEM'),
    business_objective CLOB,
    owner_area VARCHAR2(200),
    criticality VARCHAR2(20)
        CHECK (criticality IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    system_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL
        CHECK (system_status IN ('PLANNED', 'ACTIVE', 'DEPRECATED', 'RETIRED')),
    go_live_date DATE,
    end_of_life_date DATE,
    FOREIGN KEY (component_id, component_type)
        REFERENCES catalog_component (component_id, component_type) ON DELETE CASCADE,
    CHECK (end_of_life_date IS NULL OR go_live_date IS NULL OR end_of_life_date >= go_live_date)
);

CREATE TABLE api_detail (
    component_id NUMBER(19) PRIMARY KEY,
    component_type VARCHAR2(30) DEFAULT 'API' NOT NULL CHECK (component_type = 'API'),
    api_version VARCHAR2(50),
    url VARCHAR2(2000),
    protocol VARCHAR2(30),
    authentication_method VARCHAR2(100),
    sla_description CLOB,
    FOREIGN KEY (component_id, component_type)
        REFERENCES catalog_component (component_id, component_type) ON DELETE CASCADE
);

CREATE TABLE database_detail (
    component_id NUMBER(19) PRIMARY KEY,
    component_type VARCHAR2(30) DEFAULT 'DATABASE' NOT NULL CHECK (component_type = 'DATABASE'),
    engine VARCHAR2(100) NOT NULL,
    engine_version VARCHAR2(100),
    instance_name VARCHAR2(200),
    schema_name VARCHAR2(200),
    FOREIGN KEY (component_id, component_type)
        REFERENCES catalog_component (component_id, component_type) ON DELETE CASCADE
);

CREATE TABLE infrastructure_detail (
    component_id NUMBER(19) PRIMARY KEY,
    component_type VARCHAR2(30) DEFAULT 'INFRASTRUCTURE' NOT NULL
        CHECK (component_type = 'INFRASTRUCTURE'),
    hostname VARCHAR2(255),
    ip_address VARCHAR2(45),
    operating_system VARCHAR2(200),
    hosting_model VARCHAR2(20)
        CHECK (hosting_model IN ('CLOUD', 'ON_PREMISE')),
    FOREIGN KEY (component_id, component_type)
        REFERENCES catalog_component (component_id, component_type) ON DELETE CASCADE
);

CREATE TABLE system_deployment (
    deployment_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_id NUMBER(19) NOT NULL REFERENCES system_detail (component_id) ON DELETE CASCADE,
    environment VARCHAR2(20) NOT NULL
        CHECK (environment IN ('DEVELOPMENT', 'TEST', 'QA', 'STAGING', 'PRODUCTION', 'DR')),
    url VARCHAR2(2000),
    UNIQUE (component_id, environment)
);

CREATE TABLE person (
    person_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(200) NOT NULL,
    email VARCHAR2(320),
    organization VARCHAR2(200),
    is_active CHAR(1) DEFAULT 'Y' NOT NULL
        CHECK (is_active IN ('Y', 'N')),
    UNIQUE (email)
);

CREATE TABLE responsibility_role (
    role_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code VARCHAR2(40) NOT NULL UNIQUE,
    role_name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE system_responsibility (
    component_id NUMBER(19) NOT NULL REFERENCES system_detail (component_id) ON DELETE CASCADE,
    person_id NUMBER(19) NOT NULL REFERENCES person (person_id),
    role_id NUMBER(19) NOT NULL REFERENCES responsibility_role (role_id),
    notes CLOB,
    PRIMARY KEY (component_id, person_id, role_id)
);

CREATE TABLE technology (
    technology_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR2(30) NOT NULL
        CHECK (category IN ('LANGUAGE', 'FRAMEWORK', 'DATABASE', 'FRONTEND', 'BACKEND',
                            'MESSAGING', 'CONTAINER', 'ORCHESTRATION', 'MONITORING', 'OTHER')),
    name VARCHAR2(200) NOT NULL,
    UNIQUE (category, name)
);

CREATE TABLE component_technology (
    component_id NUMBER(19) NOT NULL REFERENCES catalog_component (component_id) ON DELETE CASCADE,
    technology_id NUMBER(19) NOT NULL REFERENCES technology (technology_id),
    version VARCHAR2(100),
    is_primary CHAR(1) DEFAULT 'N' NOT NULL
        CHECK (is_primary IN ('Y', 'N')),
    PRIMARY KEY (component_id, technology_id)
);

CREATE TABLE dependency_type (
    dependency_type_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_code VARCHAR2(40) NOT NULL UNIQUE,
    type_name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE dependency (
    dependency_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin_component_id NUMBER(19) NOT NULL REFERENCES catalog_component (component_id),
    target_component_id NUMBER(19) NOT NULL REFERENCES catalog_component (component_id),
    dependency_type_id NUMBER(19) NOT NULL REFERENCES dependency_type (dependency_type_id),
    dependency_scope VARCHAR2(10) NOT NULL
        CHECK (dependency_scope IN ('INTERNAL', 'EXTERNAL')),
    criticality VARCHAR2(20)
        CHECK (criticality IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    description CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CHECK (origin_component_id <> target_component_id)
);

CREATE TABLE data_flow (
    data_flow_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dependency_id NUMBER(19) NOT NULL REFERENCES dependency (dependency_id) ON DELETE CASCADE,
    data_name VARCHAR2(200) NOT NULL,
    periodicity VARCHAR2(100),
    sensitivity VARCHAR2(20)
        CHECK (sensitivity IN ('PUBLIC', 'INTERNAL', 'CONFIDENTIAL', 'RESTRICTED')),
    data_format VARCHAR2(100),
    description CLOB
);

CREATE INDEX ix_dependency_origin ON dependency (origin_component_id);
CREATE INDEX ix_dependency_target ON dependency (target_component_id);
CREATE INDEX ix_dependency_type ON dependency (dependency_type_id);
CREATE INDEX ix_system_resp_person ON system_responsibility (person_id);
CREATE INDEX ix_component_tech_technology ON component_technology (technology_id);
CREATE INDEX ix_data_flow_dependency ON data_flow (dependency_id);

